const localeFiles = [
  'zh-cn', 'zh-tw', 'ar', 'cs', 'es', 'hi', 'id',
  'it', 'nl', 'pl', 'ru', 'sv', 'th', 'tr', 'vi'
];

function setNestedValue(obj, keyPath, value) {
  const keys = keyPath.split('.');
  let current = obj;
  for (let i = 0; i < keys.length - 1; i++) {
    const key = keys[i];
    if (!current[key] || typeof current[key] !== 'object') {
      current[key] = {};
    }
    current = current[key];
  }
  current[keys[keys.length - 1]] = value;
}

const localesDir = path.join(__dirname, '..', 'app', 'locales');

for (const locale of localeFiles) {
  const filePath = path.join(localesDir, `${locale}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  
  let added = 0;
  for (const [key, translationsForKey] of Object.entries(translations)) {
    const translation = translationsForKey[locale];
    if (translation) {
      setNestedValue(data, key, translation);
      added++;
    }
  }
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n');
  console.log(`${locale}: added ${added} keys`);
}

console.log('Done!');
